"""ProviderServer: an inference provider modeled as the attacker.

When generating a response it switches between honest(M) and cheat(M'), and adds:
  (a) randomized substitution: M with probability p_honest, else M'
  (b) audit evasion: if a known canary query is detected, respond with M
Every mode issues and signs a protocol-conformant receipt (the signing key is
provider-controlled -- detection is done by sketch consistency; see hooks/sketch).

Attacker forgery capabilities modeled here:
  - For a response generated by M', build the "best possible fake receipt" from M''s
    own hidden_states. If the layer counts differ, use a proportional mapping (map
    shallow layers to shallow layers) to look as similar as possible.
  - Replay a past honest receipt (shown to be rejected by the structural check in tests).
What the attacker cannot do: learn M's activations without running M (if it could,
it could just serve M) -- this is the crux of Assay's security.

[Claim: unevadable] The evasive mode completely defeats canary-based external audits,
but Assay puts a receipt on ordinary user requests too, so evasion is structurally
impossible.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional, Sequence, Set, Tuple

import numpy as np
import torch
from torch import nn

from assay.hooks import capture_hidden_states, num_layers
from assay.nondeterminism import NondeterminismModel
from assay.sketch import ActivationSketcher, Receipt


@dataclass
class ServerResponse:
    request_id: str
    output_ids: List[int]
    receipt: Receipt
    model_used: str  # "M" or "M'" (ground-truth label for the benchmark; unobservable in production)


class ProviderServer:
    """An attacker-modeled server switchable between honest / cheat / random / evasive."""

    MODES = ("honest", "cheat", "random", "evasive")

    def __init__(
        self,
        model_m: nn.Module,
        model_mp: Optional[nn.Module],
        sketcher: ActivationSketcher,
        mode: str = "honest",
        p_honest: float = 0.9,
        canaries: Optional[Sequence[torch.Tensor]] = None,
        jitter: Optional[NondeterminismModel] = None,
        gen_len: int = 16,
        seed: int = 0,
        model_claim: str = "M",
    ):
        assert mode in self.MODES, f"mode must be one of {self.MODES}"
        if mode != "honest" and model_mp is None:
            raise ValueError("cheat modes require model_mp")
        self.model_m = model_m
        self.model_mp = model_mp
        self.sketcher = sketcher
        self.mode = mode
        self.p_honest = p_honest
        self.jitter = jitter
        self.gen_len = gen_len
        self.model_claim = model_claim
        self._rng = np.random.default_rng(seed)
        # Audit evasion: the strongest setting, where the attacker holds the set of known canaries (token sequences)
        self._canary_keys: Set[Tuple[int, ...]] = set()
        for c in canaries or []:
            self._canary_keys.add(tuple(int(x) for x in c.flatten().tolist()))

    # -- model switching (attacker logic) -----------------------------------

    def _decide(self, prompt_ids: torch.Tensor) -> Tuple[nn.Module, str]:
        """Decide whether to answer this request with M or M'.

        evasive: exact canary match detected -> answer with M (looks honest to the external audit).
        random:  M with probability p_honest (dilutes a sampling audit's expected
                 detection time by a factor of 1/(1-p_honest)).

        [Claim: unevadable] Both modes are aimed squarely at sampling audits, and both work
        against one: evasion makes canary queries useless, randomization makes them slow.
        Neither helps against per-request receipts, because the decision this method makes
        is recorded in the receipt of the very request it was made for.
        """
        if self.mode == "honest":
            return self.model_m, "M"
        if self.mode == "cheat":
            return self.model_mp, "M'"
        if self.mode == "random":
            if self._rng.random() < self.p_honest:
                return self.model_m, "M"
            return self.model_mp, "M'"
        # evasive
        key = tuple(int(x) for x in prompt_ids.flatten().tolist())
        if key in self._canary_keys:
            return self.model_m, "M"
        return self.model_mp, "M'"

    # -- generation ---------------------------------------------------------

    @torch.no_grad()
    def _generate(self, model: nn.Module, prompt_ids: torch.Tensor) -> List[int]:
        ids = prompt_ids.flatten().unsqueeze(0)
        out = model.generate(
            ids,
            attention_mask=torch.ones_like(ids),
            max_new_tokens=self.gen_len,
            do_sample=False,
            pad_token_id=getattr(model.config, "pad_token_id", None) or getattr(model.config, "eos_token_id", 0) or 0,
        )
        return [int(x) for x in out[0, ids.shape[1]:].tolist()]

    def _layer_map(self, model: nn.Module):
        """Claimed-layer index -> hidden_states index of the model that actually ran.

        Identity when honest (M). An attacker using an M' with a different layer
        count offers the "most plausibly corresponding" layer via a proportional
        mapping (a best-effort forgery).

        [Claim: unevadable] This is deliberately the attacker's *best* move, so the
        detection result is not an artifact of a strawman: even when M' hands over the
        layer that should look most like the claimed one, the sketches do not agree.
        """
        n_claim = num_layers(self.model_m)
        n_actual = num_layers(model)
        if n_actual == n_claim:
            return lambda l: l
        return lambda l: max(1, min(n_actual, int(round(l * n_actual / n_claim))))

    # -- request handling ----------------------------------------------------

    def handle(self, request_id: str, prompt_ids: torch.Tensor) -> ServerResponse:
        """Handle one request: choose model -> generate -> issue receipt (all under jitter).

        The receipt is computed from the hidden_states of the model that actually
        ran -- if M' ran, M's activations are unknowable, so a "correct receipt"
        cannot be produced.
        [Claim: unevadable] This is the basis of all-request verification security.
        """
        model, used = self._decide(prompt_ids)
        import contextlib

        ctx = self.jitter.applied_to(model) if self.jitter is not None else contextlib.nullcontext()
        with ctx:
            output_ids = self._generate(model, prompt_ids)
            full_ids = torch.cat([prompt_ids.flatten(), torch.as_tensor(output_ids, dtype=torch.long)])
            hidden_states = capture_hidden_states(model, full_ids)
        receipt = self.sketcher.build_receipt(
            request_id=request_id,
            model_claim=self.model_claim,
            prompt_ids=[int(x) for x in prompt_ids.flatten().tolist()],
            output_ids=output_ids,
            hidden_states=hidden_states,
            layer_map=self._layer_map(model),
        )
        return ServerResponse(request_id=request_id, output_ids=output_ids, receipt=receipt, model_used=used)
